import { Component, ViewChild, ElementRef } from '@angular/core';
import { ApiService } from '../../../services/api.service';
import { NotificationService } from '../../../services/notification.service';
import { AuthService } from '../../../services/auth.service';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AppModule } from '../../../app.module';

@Component({
  selector: 'app-pending-quotes',
  standalone: true,
  imports: [AppModule],
  templateUrl: './pending-quotes.component.html',
  styleUrl: './pending-quotes.component.less'
})
export class PendingQuotesComponent {
  @ViewChild('reportContent') reportContent!: ElementRef;

  isLoading: boolean = false;
  isExporting: boolean = false;
  errorMessage: string | null = null;
  pendingQuotes: any[] = [];
  currentDate: Date = new Date();
  generatedBy: string = '';
  totalAmount: number = 0;

  constructor(
    private apiService: ApiService,
    private notification: NotificationService,
    private authService: AuthService
  ) {
    this.generatedBy = this.authService.user?.name || '';
    this.loadPendingQuotes();
  }

  loadPendingQuotes(): void {
    this.isLoading = true;
    this.errorMessage = null;
    this.totalAmount = 0;

    this.apiService.get_pending_quotes().subscribe({
      next: (response) => {
        this.pendingQuotes = response;

        // Calculate total amount
        this.pendingQuotes.forEach(quote => {
          this.totalAmount += quote.total_cost;
        });

        if (this.pendingQuotes.length === 0) {
          this.errorMessage = 'No pending quotes found';
        }

        this.isLoading = false;
      },
      error: (err) => {
        console.error('Error loading pending quotes:', err);
        this.errorMessage = 'Failed to load pending quotes data';
        this.isLoading = false;
      }
    });
  }

  async exportToPDF() {
    this.isExporting = true;

    try {
      const doc = new jsPDF('p', 'mm', 'a4');
      const margin = 15;
      const pageWidth = doc.internal.pageSize.getWidth();
      let yPos = margin;

      // Add logo
      const logoData = await this.getLogoData('assets/images/logo.png');
      if (logoData) {
        const logoWidth = 30;
        const logoHeight = (logoData.height * logoWidth) / logoData.width;
        const logoX = (pageWidth - logoWidth) / 2;

        doc.addImage(
          logoData.dataUrl,
          'PNG',
          logoX,
          yPos,
          logoWidth,
          logoHeight
        );
        yPos += logoHeight + 5;
      }

      // Report title
      doc.setFontSize(18);
      doc.setFont('helvetica', 'bold');
      doc.text('Pending Quotes Report', pageWidth / 2, yPos, { align: 'center' });
      yPos += 10;

      // Subtitle
      doc.setFontSize(12);
      doc.setFont('helvetica', 'normal');
      doc.text('List of all outstanding quotes awaiting payment', pageWidth / 2, yPos, { align: 'center' });
      yPos += 15;

      // Metadata
      doc.setFontSize(10);
      doc.text(`Date Generated: ${this.currentDate.toLocaleDateString()}`, margin, yPos);
      doc.text(`Generated By: ${this.generatedBy}`, pageWidth - margin, yPos, { align: 'right' });
      yPos += 10;

      // Prepare table data
      const tableData = this.pendingQuotes.map(quote => [
        quote.quotation_number || 'N/A',
        quote.company_name,
        quote.telephone,
        this.formatCurrency(quote.total_cost)
      ]);

      // Generate table
      autoTable(doc, {
        head: [['Quote #', 'Company', 'Telephone', 'Amount (R)']],
        body: tableData,
        startY: yPos,
        margin: { left: margin, right: margin },
        styles: {
          fontSize: 10,
          cellPadding: 3,
          valign: 'middle'
        },
        headStyles: {
          fillColor: [52, 152, 219],  // Blue header
          textColor: 255,
          fontStyle: 'bold',
          halign: 'center'
        },
        columnStyles: {
          0: { cellWidth: 30 },
          1: { cellWidth: 70 },
          2: { cellWidth: 45 },
          3: { cellWidth: 35, halign: 'right' }
        },
        theme: 'grid'
      });

      // Add total row
      const finalY = (doc as any).lastAutoTable.finalY;
// In exportToPDF() method:
      autoTable(doc, {
        body: [
          ['', '', 'Total Outstanding:', this.formatCurrency(this.totalAmount)]
        ],
        startY: finalY,
        margin: { left: margin, right: margin },
        styles: {
          fontSize: 11,
          cellPadding: 3,
          fontStyle: 'bold',
          fillColor: [230, 244, 253]  // Light blue background
        },
        columnStyles: {
          0: { cellWidth: 30, fillColor: 255 },  // Fixed: use number
          1: { cellWidth: 70, fillColor: 255 },  // Fixed: use number
          2: { cellWidth: 45, halign: 'right' },
          3: { cellWidth: 35, halign: 'right' }
        }
      });

      // Footer
      const footerY = doc.internal.pageSize.getHeight() - 15;
      doc.setFontSize(9);
      doc.text('Vault Vision', pageWidth / 2, footerY, { align: 'center' });

      // Save PDF
      const fileName = `pending-quotes-${new Date().toISOString().slice(0, 10)}.pdf`;
      doc.save(fileName);

    } catch (error) {
      console.error('Export error:', error);
      this.notification.showError('Export Failed', 'Could not generate PDF');
    } finally {
      this.isExporting = false;
    }
  }

  private getLogoData(url: string): Promise<{ dataUrl: string; width: number; height: number } | null> {
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = 'Anonymous';
      img.src = url;

      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (!ctx) return resolve(null);

        canvas.width = img.width;
        canvas.height = img.height;
        ctx.drawImage(img, 0, 0);

        resolve({
          dataUrl: canvas.toDataURL('image/png'),
          width: img.width,
          height: img.height
        });
      };

      img.onerror = () => resolve(null);
    });
  }

  formatCurrency(value: number): string {
    return value.toLocaleString('en-ZA', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2
    });
  }
}
