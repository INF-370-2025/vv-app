// low-stock.component.ts
import { Component } from '@angular/core';
import { ApiService } from '../../../services/api.service';
import { NotificationService } from '../../../services/notification.service';
import { AuthService } from '../../../services/auth.service';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AppModule } from '../../../app.module';

@Component({
  selector: 'app-low-stock',
  standalone: true,
  imports: [AppModule],
  templateUrl: './low-stock.component.html',
  styleUrls: ['./low-stock.component.less']
})
export class LowStockComponent {
  isLoading: boolean = false;
  isExporting: boolean = false;
  errorMessage: string | null = null;
  lowStockItems: any[] = [];
  currentDate: Date = new Date();
  generatedBy: string = '';
  criticalItems: number = 0;
  warningItems: number = 0;

  constructor(
    private apiService: ApiService,
    private notification: NotificationService,
    private authService: AuthService
  ) {
    this.generatedBy = this.authService.user?.name || '';
    this.loadLowStock();
  }

  loadLowStock(): void {
    this.isLoading = true;
    this.errorMessage = null;
    this.currentDate = new Date();
    this.criticalItems = 0;
    this.warningItems = 0;

    this.apiService.get_all_stock().subscribe({
      next: (response) => {
        const allStock = response.map((item: any) => ({
          ...item.stock_details,
          stock_id: item.stock_id,
          created_at: item.created_at
        }));

        this.lowStockItems = allStock.filter((item: any) => item.stock_level < 50);

        // Count critical and warning items
        this.lowStockItems.forEach(item => {
          if (item.stock_level < 10) {
            this.criticalItems++;
          } else {
            this.warningItems++;
          }
        });

        if (this.lowStockItems.length === 0) {
          this.errorMessage = 'No stock items below 50 units';
        }

        this.isLoading = false;
      },
      error: (err) => {
        console.error('Error loading stock:', err);
        this.errorMessage = 'Failed to load stock data';
        this.isLoading = false;
      }
    });
  }

async exportToPDF() {
  this.isExporting = true;

  try {
    const doc = new jsPDF('p', 'mm', 'a4');
    const margin = 15;
    const pageWidth = doc.internal.pageSize.getWidth();
    let yPos = margin;

    // Add logo
    const logoData = await this.getLogoData('assets/images/logo.png');
    if (logoData) {
      const logoWidth = 30;
      const logoHeight = (logoData.height * logoWidth) / logoData.width;
      const logoX = (pageWidth - logoWidth) / 2;

      doc.addImage(
        logoData.dataUrl,
        'PNG',
        logoX,
        yPos,
        logoWidth,
        logoHeight
      );
      yPos += logoHeight + 5;
    }

    // Add report title
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(23, 114, 109);
    doc.text('Low Stock Report', pageWidth / 2, yPos, { align: 'center' });
    yPos += 8;

    // Add subtitle
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(89, 89, 89);
    doc.text('Items with stock levels below 50 units', pageWidth / 2, yPos, { align: 'center' });
    yPos += 15;

    // Add metadata
    doc.setFontSize(10);
    doc.setTextColor(0, 0, 0);
    doc.text(`Date Generated: ${this.currentDate.toLocaleDateString()}`, margin, yPos);
    doc.text(`Generated By: ${this.generatedBy}`, pageWidth - margin, yPos, { align: 'right' });
    yPos += 8;

    doc.text(`Critical Items (<10): ${this.criticalItems}`, margin, yPos);
    doc.text(`Warning Items (10-49): ${this.warningItems}`, pageWidth - margin, yPos, { align: 'right' });
    yPos += 15;

    // Prepare table data
    const tableData = this.lowStockItems.map(item => [
      item.name,
      item.stock_level  // Keep as number
    ]);

    // Generate table
    autoTable(doc, {
      head: [['Item Name', 'Stock Level']],
      body: tableData,
      startY: yPos,
      margin: { left: margin, right: margin },
      styles: {
        fontSize: 10,
        cellPadding: 6,
        valign: 'middle'
      },
      headStyles: {
        fillColor: [41, 128, 185],
        textColor: 255,
        fontStyle: 'bold',
        halign: 'center'
      },
      columnStyles: {
        0: { cellWidth: 120, halign: 'left' },
        1: { cellWidth: 30, halign: 'center' }
      },
      theme: 'grid',
      didDrawCell: (data) => {
        // Add colored blocks for stock level indicators
        if (data.column.index === 1 && data.cell.raw !== null && data.cell.raw !== undefined) {
          try {
            // Handle both string and number types
            const stockLevel = typeof data.cell.raw === 'number'
              ? data.cell.raw
              : parseInt(data.cell.raw.toString());

            if (!isNaN(stockLevel)) {
              let r = 0, g = 0, b = 0;

              if (stockLevel < 10) {
                r = 245; g = 34; b = 45;    // Red
              } else {
                r = 250; g = 173; b = 20;   // Orange
              }

              // Draw colored block filling the cell
              doc.setFillColor(r, g, b);
              doc.rect(
                data.cell.x,
                data.cell.y,
                data.cell.width,
                data.cell.height,
                'F'
              );

              // Add text centered in the cell
              doc.setFontSize(10);
              doc.setTextColor(0, 0, 0);
              doc.text(
                stockLevel.toString(),
                data.cell.x + data.cell.width / 2,
                data.cell.y + data.cell.height / 2 + 2,
                { align: 'center', baseline: 'middle' }
              );

              return true; // Skip default rendering
            }
          } catch (e) {
            console.warn('Error drawing stock level cell', e);
          }
        }
        return false;
      }
    });

    // Add footer
    const footerY = doc.internal.pageSize.getHeight() - 15;
    doc.setFontSize(9);
    doc.text('Vault Vision - Inventory Management System', pageWidth / 2, footerY, { align: 'center' });

    // Save PDF
    doc.save(`low-stock-report-${new Date().toISOString().slice(0, 10)}.pdf`);

  } catch (error) {
    console.error('Export error:', error);
    this.notification.showError('Export Failed', 'Could not generate PDF');
  } finally {
    this.isExporting = false;
  }
}

  private getLogoData(url: string): Promise<{ dataUrl: string; width: number; height: number } | null> {
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = 'Anonymous';
      img.src = url;

      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (!ctx) return resolve(null);

        canvas.width = img.width;
        canvas.height = img.height;
        ctx.drawImage(img, 0, 0);

        resolve({
          dataUrl: canvas.toDataURL('image/png'),
          width: img.width,
          height: img.height
        });
      };

      img.onerror = () => {
        console.warn('Could not load logo');
        resolve(null);
      };
    });
  }

  getStockLevelColor(stockLevel: number): string {
    if (stockLevel < 10) return '#f5222d';
    if (stockLevel < 50) return '#faad14';
    return '#52c41a';
  }
}
