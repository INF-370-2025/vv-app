import { Component, ViewChild, ElementRef } from '@angular/core';
import { ApiService } from '../../../services/api.service';
import { NotificationService } from '../../../services/notification.service';
import jsPDF from 'jspdf';
import { AppModule } from '../../../app.module';
import { AuthService } from '../../../services/auth.service';
import autoTable from 'jspdf-autotable';

@Component({
  selector: 'app-pending-job-requests',
  standalone: true,
  imports: [AppModule],
  templateUrl: './pending-job-requests.component.html',
  styleUrl: './pending-job-requests.component.less'
})
export class PendingJobRequestsComponent {
  @ViewChild('reportContent') reportContent!: ElementRef;

  isLoading: boolean = false;
  isExporting: boolean = false;
  errorMessage: string | null = null;
  pendingRequests: any[] = [];
  currentDate: Date = new Date();
  generatedBy: string = '';
  timeFilter: string = 'all';
  totalRequests: number = 0;

  constructor(
    private apiService: ApiService,
    private notification: NotificationService,
    private authService: AuthService
  ) {
    this.generatedBy = this.authService.user?.name || '';
    this.loadPendingRequests();
  }

  loadPendingRequests(): void {
    this.isLoading = true;
    this.errorMessage = null;
    this.currentDate = new Date();

    this.apiService.get_pending_job_requests(this.timeFilter).subscribe({
    next: (response) => {
      if (!Array.isArray(response)) {
        console.error('Unexpected API response:', response);
        this.errorMessage = 'Invalid response from server';
        this.isLoading = false;
        return;
      }

      this.pendingRequests = response.map((req: any) => {
        let customerName = 'N/A';

        if (req.customers) {
          if (req.customers.company_name) {
            customerName = req.customers.company_name;
          } else if (req.customers.user) {
            customerName = `${req.customers.user.name || ''} ${req.customers.user.surname || ''}`.trim();
          }
        }

        return {
          ...req,
          customer_name: customerName
        };
      });

      this.totalRequests = this.pendingRequests.length;

      if (this.pendingRequests.length === 0) {
        this.errorMessage = 'No pending job requests found';
      }

      this.isLoading = false;
    },
      error: (err) => {
        console.error('Error loading pending job requests:', err);
        this.errorMessage = 'Failed to load pending job requests data';
        this.isLoading = false;
      }
    });
  }


  onTimeFilterChange(): void {
    this.loadPendingRequests();
  }

  async exportToPDF() {
    this.isExporting = true;

    try {
      // Landscape A4
      const doc = new jsPDF('l', 'mm', 'a4');
      const margin = 15;
      const pageWidth = doc.internal.pageSize.getWidth();
      let yPos = margin;

      // Add logo
      const logoData = await this.getLogoData('assets/images/logo.png');
      if (logoData) {
        const logoWidth = 30;
        const logoHeight = (logoData.height * logoWidth) / logoData.width;
        const logoX = (pageWidth - logoWidth) / 2;
        doc.addImage(logoData.dataUrl, 'PNG', logoX, yPos, logoWidth, logoHeight);
        yPos += logoHeight + 5;
      }

      // Title & subtitle
      doc.setFontSize(18);
      doc.setFont('helvetica', 'bold');
      doc.text('Pending Job Requests Report', pageWidth / 2, yPos, { align: 'center' });
      yPos += 10;

      doc.setFontSize(12);
      doc.setFont('helvetica', 'normal');
      doc.text(`Time Period: ${this.getFilterDisplayName()}`, pageWidth / 2, yPos, { align: 'center' });
      yPos += 15;

      // Metadata
      doc.setFontSize(10);
      doc.text(`Date Generated: ${this.currentDate.toLocaleDateString()}`, margin, yPos);
      doc.text(`Generated By: ${this.generatedBy}`, pageWidth - margin, yPos, { align: 'right' });
      yPos += 10;

      // Table data
      const tableData = this.pendingRequests.map(request => [
        request.job_request_id,
        request.title,
        request.customer_name,
        this.formatDate(request.created_at),
        this.formatDate(request.finish_date),
        request.quantity || 'N/A'
      ]);

      // AutoTable: landscape + auto column widths
      autoTable(doc, {
        head: [['Request ID', 'Title', 'Customer', 'Created Date', 'Finish Date', 'Quantity']],
        body: tableData,
        startY: yPos,
        margin: { left: margin, right: margin },
        tableWidth: 'auto', // auto-fit to page width
        styles: { fontSize: 10, cellPadding: 3, valign: 'middle' },
        headStyles: { fillColor: [41, 128, 185], textColor: 255, fontStyle: 'bold', halign: 'center' },
        columnStyles: {
          0: { cellWidth: 'auto' },
          1: { cellWidth: 'auto' },
          2: { cellWidth: 'auto' },
          3: { cellWidth: 'auto' },
          4: { cellWidth: 'auto' },
          5: { cellWidth: 'auto', halign: 'right' }
        },
        theme: 'grid'
      });

      // Total row
      const finalY = (doc as any).lastAutoTable.finalY;
      autoTable(doc, {
        body: [['', '', '', '', 'Total Requests:', this.totalRequests.toString()]],
        startY: finalY,
        margin: { left: margin, right: margin },
        styles: { fontSize: 11, cellPadding: 3, fontStyle: 'bold', fillColor: [246, 255, 237] },
        columnStyles: {
          0: { cellWidth: 'auto', fillColor: [255, 255, 255] },
          1: { cellWidth: 'auto', fillColor: [255, 255, 255] },
          2: { cellWidth: 'auto', fillColor: [255, 255, 255] },
          3: { cellWidth: 'auto', fillColor: [255, 255, 255] },
          4: { cellWidth: 'auto', halign: 'right' },
          5: { cellWidth: 'auto', halign: 'right' }
        },
        theme: 'grid'
      });

      // Footer
      const footerY = doc.internal.pageSize.getHeight() - 15;
      doc.setFontSize(9);
      doc.text('Vault Vision', pageWidth / 2, footerY, { align: 'center' });

      // Save PDF
      doc.save(`pending-job-requests-${new Date().toISOString().slice(0, 10)}.pdf`);

    } catch (error) {
      console.error('Export error:', error);
      this.notification.showError('Export Failed', 'Could not generate PDF');
    } finally {
      this.isExporting = false;
    }
  }


  private getLogoData(url: string): Promise<{ dataUrl: string; width: number; height: number } | null> {
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = 'Anonymous';
      img.src = url;

      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (!ctx) return resolve(null);

        canvas.width = img.width;
        canvas.height = img.height;
        ctx.drawImage(img, 0, 0);

        resolve({
          dataUrl: canvas.toDataURL('image/png'),
          width: img.width,
          height: img.height
        });
      };

      img.onerror = () => {
        console.warn('Could not load logo');
        resolve(null);
      };
    });
  }

  formatDate(dateString: string): string {
    if (!dateString) return 'N/A';
    const date = new Date(dateString);
    return date.toLocaleDateString();
  }

  getFilterDisplayName(): string {
    switch(this.timeFilter) {
      case 'week': return 'This Week';
      case 'month': return 'This Month';
      case 'year': return 'This Year';
      default: return 'All Time';
    }
  }
}
