import { Component, ViewChild, ElementRef } from '@angular/core';
import { ApiService } from '../../../services/api.service';
import { NotificationService } from '../../../services/notification.service';
import jsPDF from 'jspdf';
import { AppModule } from '../../../app.module';
import { AuthService } from '../../../services/auth.service';
import autoTable from 'jspdf-autotable';

@Component({
  selector: 'app-unpaid-invoices',
  standalone: true,
  imports: [AppModule],
  templateUrl: './unpaid-invoices.component.html',
  styleUrl: './unpaid-invoices.component.less'
})

export class UnpaidInvoicesComponent {
  @ViewChild('reportContent') reportContent!: ElementRef;

  isLoading: boolean = false;
  isExporting: boolean = false;
  errorMessage: string | null = null;
  unpaidInvoices: any[] = [];
  currentDate: Date = new Date();
  generatedBy: string = '';
  totalAmount: number = 0;

  constructor(
    private apiService: ApiService,
    private notification: NotificationService,
    private authService: AuthService
  ) {
    this.generatedBy = this.authService.user?.name || '';
    this.loadUnpaidInvoices();
  }

  loadUnpaidInvoices(): void {
    this.isLoading = true;
    this.errorMessage = null;
    this.currentDate = new Date();
    this.totalAmount = 0;

    this.apiService.get_unpaid_invoices().subscribe({
      next: (response) => {
        this.unpaidInvoices = response;

        // Calculate total amount
        this.unpaidInvoices.forEach(invoice => {
          this.totalAmount += invoice.total;
        });

        if (this.unpaidInvoices.length === 0) {
          this.errorMessage = 'No unpaid invoices found';
        }

        this.isLoading = false;
      },
      error: (err) => {
        console.error('Error loading unpaid invoices:', err);
        this.errorMessage = 'Failed to load unpaid invoices data';
        this.isLoading = false;
      }
    });
  }

async exportToPDF() {
  this.isExporting = true;

  try {
    const doc = new jsPDF('p', 'mm', 'a4');
    const margin = 15;
    const pageWidth = doc.internal.pageSize.getWidth();
    let yPos = margin;

    // Add logo
    const logoData = await this.getLogoData('assets/images/logo.png');
    if (logoData) {
      const logoWidth = 30; // Fixed width in mm
      const logoHeight = (logoData.height * logoWidth) / logoData.width; // Maintain aspect ratio
      const logoX = (pageWidth - logoWidth) / 2; // Center horizontally

      doc.addImage(
        logoData.dataUrl,
        'PNG',
        logoX,
        yPos,
        logoWidth,
        logoHeight
      );
      yPos += logoHeight + 5; // Add space after logo
    }

    // Add report title
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text('Unpaid Invoices Report', pageWidth / 2, yPos, { align: 'center' });
    yPos += 10;

    // Add subtitle
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text('List of all outstanding invoices', pageWidth / 2, yPos, { align: 'center' });
    yPos += 15;

    // Add metadata
    doc.setFontSize(10);
    doc.text(`Date Generated: ${this.currentDate.toLocaleDateString()}`, margin, yPos);
    doc.text(`Generated By: ${this.generatedBy}`, pageWidth - margin, yPos, { align: 'right' });
    yPos += 10;

    // Prepare table data
    const tableData = this.unpaidInvoices.map(invoice => [
      invoice.invoice_number,
      invoice.company_name,
      invoice.telephone,
      this.formatCurrency(invoice.total)
    ]);

    // Generate table
    autoTable(doc, {
      head: [['Invoice #', 'Company', 'Telephone', 'Amount (R)']],
      body: tableData,
      startY: yPos,
      margin: { left: margin, right: margin },
      styles: {
        fontSize: 10,
        cellPadding: 3,
        valign: 'middle'
      },
      headStyles: {
        fillColor: [41, 128, 185],
        textColor: 255,
        fontStyle: 'bold',
        halign: 'center'
      },
      columnStyles: {
        0: { cellWidth: 35 },
        1: { cellWidth: 70 },
        2: { cellWidth: 45 },
        3: { cellWidth: 35, halign: 'right' }
      },
      theme: 'grid'
    });

    // Add total row
    const finalY = (doc as any).lastAutoTable.finalY;
    autoTable(doc, {
      body: [
        ['', '', 'Total Outstanding:', this.formatCurrency(this.totalAmount)]
      ],
      startY: finalY,
      margin: { left: margin, right: margin },
      styles: {
        fontSize: 11,
        cellPadding: 3,
        fontStyle: 'bold',
        fillColor: [246, 255, 237]
      },
      columnStyles: {
        0: { cellWidth: 35, fillColor: [255, 255, 255] },
        1: { cellWidth: 70, fillColor: [255, 255, 255] },
        2: { cellWidth: 45, halign: 'right' },
        3: { cellWidth: 35, halign: 'right' }
      },
      theme: 'grid'
    });

    // Add footer
    const footerY = doc.internal.pageSize.getHeight() - 15;
    doc.setFontSize(9);
    doc.text('Vault Vision', pageWidth / 2, footerY, { align: 'center' });

    // Save PDF
    doc.save(`unpaid-invoices-${new Date().toISOString().slice(0, 10)}.pdf`);

  } catch (error) {
    console.error('Export error:', error);
    this.notification.showError('Export Failed', 'Could not generate PDF');
  } finally {
    this.isExporting = false;
  }
}

private getLogoData(url: string): Promise<{ dataUrl: string; width: number; height: number } | null> {
  return new Promise((resolve) => {
    const img = new Image();
    img.crossOrigin = 'Anonymous';
    img.src = url;

    img.onload = () => {
      const canvas = document.createElement('canvas');
      const ctx = canvas.getContext('2d');
      if (!ctx) return resolve(null);

      canvas.width = img.width;
      canvas.height = img.height;
      ctx.drawImage(img, 0, 0);

      resolve({
        dataUrl: canvas.toDataURL('image/png'),
        width: img.width,
        height: img.height
      });
    };

    img.onerror = () => {
      console.warn('Could not load logo');
      resolve(null);
    };
  });
}

  formatCurrency(value: number): string {
    return value.toLocaleString('en-ZA', { minimumFractionDigits: 2 });
  }
}
